const EU_LOCALE = 'de-DE';

// Full-precision euro amount, NO abbreviation — used in tooltips & KPI cards
export function fmtFull(n) {
  if (n === null || n === undefined || isNaN(n)) return '—';
  const sign = n < 0 ? '-' : '';
  const abs = Math.abs(Math.round(n));
  return sign + '€' + abs.toLocaleString(EU_LOCALE);
}

// Compact euro amount for space-constrained chart axes (EU separators)
export function fmt(n) {
  if (n === null || n === undefined || isNaN(n)) return '—';
  const sign = n < 0 ? '-' : '';
  const abs = Math.abs(n);
  if (abs >= 1e6) return sign + '€' + (abs / 1e6).toLocaleString(EU_LOCALE, {minimumFractionDigits:0, maximumFractionDigits:2}) + 'M';
  return sign + '€' + Math.round(abs).toLocaleString(EU_LOCALE);
}

export function fmtN(n) {
  if (n === null || n === undefined || isNaN(n)) return '—';
  return Math.round(n).toLocaleString(EU_LOCALE);
}

export function fmtNum(n) {
  if (n === null || n === undefined || isNaN(n)) return '—';
  const sign = n < 0 ? '-' : '';
  const abs = Math.abs(n);
  if (abs >= 1e6) return sign + (abs / 1e6).toLocaleString(EU_LOCALE, {minimumFractionDigits:0, maximumFractionDigits:2}) + 'M';
  return sign + Math.round(abs).toLocaleString(EU_LOCALE);
}

export const legendClickHandler = function(e, legendItem, legend) {
  const index = legendItem.index;
  const ci = legend.chart;
  const meta = ci.getDatasetMeta(0);
  
  const visibleCount = meta.data.filter(d => !d.hidden).length;
  const isOnlyOneVisible = visibleCount === 1 && !meta.data[index].hidden;
  
  if (isOnlyOneVisible) {
    meta.data.forEach(d => d.hidden = false);
  } else {
    meta.data.forEach((d, i) => d.hidden = i !== index);
  }
  ci.update();
  return false;
};

export const multiLegendClickHandler = function(e, legendItem, legend) {
  const index = legendItem.datasetIndex;
  const ci = legend.chart;
  
  const visibleCount = ci.data.datasets.filter(d => !d.hidden).length;
  const isOnlyOneVisible = visibleCount === 1 && !ci.data.datasets[index].hidden;
  
  if (isOnlyOneVisible) {
    ci.data.datasets.forEach(d => d.hidden = false);
  } else {
    ci.data.datasets.forEach((d, i) => d.hidden = i !== index);
  }
  ci.update();
  return false;
};

